//! The recorded demo (platform cleanup phase 2): a real, seeded run of the real simulation,
//! saved as typed data so the web can replay it when the wasm package is not available. The
//! script (`content/demo_script.json`: a seed and the commands of each turn) is played here;
//! every reply the replay port serves is a reply this crate produced. Pure: `generate()` returns
//! the text of `web/src/sim-port/replay/recording.generated.ts`; `examples/recording.rs` writes it
//! and `tests/recording.rs` fails when the committed copy is stale.
use crate::api::Api;
use crate::command::Command;
use crate::error::{code, ApiError, ApiResult};
use crate::meta::{ActionInfo, LeverInfo};
use crate::snapshot::Snapshot;
use crate::turn::TurnResult;
use serde::{Deserialize, Serialize};

/// The script, embedded at build time.
pub const SCRIPT: &str = include_str!("../../../content/demo_script.json");

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Script {
    #[serde(rename = "_note")]
    _note: String,
    seed: u64,
    turns: Vec<Vec<Command>>,
}

/// One recorded game: the replies of the simulation to a fixed script.
#[cfg_attr(feature = "ts", derive(ts_rs::TS))]
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Recording {
    #[cfg_attr(feature = "ts", ts(type = "number"))]
    pub seed: u64,
    /// `SCHEMA_VERSION` of the wire the recording was made with.
    pub schema_version: u32,
    /// The commands played in each turn (the web shows them, so the player knows what was done).
    pub script: Vec<Vec<Command>>,
    /// `init(seed)`.
    pub initial: Snapshot,
    pub levers: Vec<LeverInfo>,
    pub actions: Vec<ActionInfo>,
    pub catalog: crate::catalog::Catalog,
    pub assumptions: Vec<crate::assumptions::AssumptionTopic>,
    pub agents: crate::assumptions::AgentsCatalog,
    /// `submitTurn(script[i])` for each turn, in order.
    pub turns: Vec<TurnResult>,
}

/// Play the script on the real simulation.
pub fn record() -> ApiResult<Recording> {
    let script: Script = serde_json::from_str(SCRIPT)
        .map_err(|e| ApiError::new(code::BAD_METADATA, format!("content/demo_script.json: {e}")))?;
    let mut api = Api::init(script.seed)?;
    let initial = api.snapshot();
    let mut turns = Vec::new();
    for cmds in &script.turns {
        turns.push(api.submit_turn(cmds)?);
    }
    Ok(Recording {
        seed: script.seed,
        schema_version: crate::SCHEMA_VERSION,
        script: script.turns,
        initial,
        levers: api.levers().to_vec(),
        actions: api.actions().to_vec(),
        catalog: api.catalog()?,
        assumptions: api.assumptions()?,
        agents: api.agents()?,
        turns,
    })
}

/// Header of the generated file.
pub const HEADER: &str = "// GENERATED by `cargo run -p sim-api --example recording` (npm run gen:recording). Do not edit.\n// A recorded run of the real simulation (content/demo_script.json); typed against the generated contract.\nimport type { Recording } from '../../contract';\n\nexport const RECORDING: Recording = ";

/// The text of the generated TypeScript file.
pub fn generate() -> ApiResult<String> {
    let json = serde_json::to_string(&record()?)
        .map_err(|e| ApiError::new(code::BAD_STATE, e.to_string()))?;
    Ok(format!("{HEADER}{json};\n"))
}
