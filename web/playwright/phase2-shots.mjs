// Usage: node playwright/phase2-shots.mjs <outDir> <url>. Platform cleanup phase 2: inspector for a firm, a home, the estate corner of the scene, and (with ?sim=replay) the recorded demo.
import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
const out = process.argv[2];
const url = process.argv[3] ?? 'http://localhost:5200/?sim=wasm&seed=7';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const errors = [];
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto(url);
await page.evaluate(() => localStorage.setItem('panels.coach.done', '1'));
await page.reload();
await page.waitForSelector('canvas');
await page.waitForTimeout(1500);
console.log('sim:', await page.evaluate(() => document.documentElement.dataset.sim));
await page.getByRole('button', { name: 'Dismiss' }).click().catch(() => {});
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` });
const play = (n) => page.evaluate((k) => { const g = window.__game; for (let i = 0; i < k; i++) { g.endTurn(); g.finishPlayback(); g.continueFromResults(); } }, n);
await shot('start');
await play(3);
await page.waitForTimeout(500);
await page.evaluate(() => { const s = window.__game.state.get().snapshot; window.__game.select({ kind: 'firm', id: s.firms.find((f) => f.active).id }); });
await page.waitForTimeout(300); await shot('inspector-firm');
await page.evaluate(() => { const s = window.__game.state.get().snapshot; window.__game.select({ kind: 'home', id: s.homes.find((h) => h.household !== null && h.owner !== 'public').id }); });
await page.waitForTimeout(300); await shot('inspector-home');
await page.evaluate(() => { const s = window.__game.state.get().snapshot; const t = s.map.tiles.find((x) => x.kind === 'fossil_plant'); window.__game.select({ kind: 'tile', x: t.x, y: t.y }); });
await page.waitForTimeout(300); await shot('inspector-plant');
await page.evaluate(() => window.__game.select(null));
for (const t of ['Policies', 'Finance']) { await page.getByRole('tab', { name: t }).click(); await page.waitForTimeout(300); await shot(`tab-${t.toLowerCase()}`); }
await page.evaluate(() => { const g = window.__game; g.rotate(1); g.rotate(1); });
await page.waitForTimeout(800); await shot('scene-estate-rotated');
console.log(errors.length ? 'console errors:\n' + errors.join('\n') : 'no console errors');
await browser.close();
