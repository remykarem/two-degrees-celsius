// Usage: node playwright/scene-keys2.mjs <mock|real>. Verifies the keyboard tile cursor (arrows, Enter places, Esc cancels) and person click/hover. Needs dev server on 5180.
import { chromium } from '@playwright/test';
const sim = process.argv[2] ?? 'mock';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto(`http://localhost:5180/?seed=42${sim === 'mock' ? '&sim=mock' : ''}`);
await page.waitForSelector('canvas');
await page.waitForTimeout(1200);
for (const name of ['Skip guide', 'Dismiss']) { const b = page.getByRole('button', { name }); if (await b.count()) await b.first().click().catch(() => {}); }
const st = () => page.evaluate(() => { const s = window.__game.state.get(); return { hover: s.hover, build: s.buildKind, draft: s.draft.map((d) => d.command.tile), sel: s.selection, phase: s.phase }; });
const check = (name, ok, extra = '') => console.log(ok ? 'PASS' : 'FAIL', name, extra);
await page.evaluate(() => { window.__game.enterPlan(); window.__game.setBuildKind('road'); });
await page.locator('canvas').focus();
await page.waitForTimeout(200);
let s = await st();
check('focus puts the cursor on the map', !!s.hover, JSON.stringify(s.hover));
const target = await page.evaluate(() => { const v = window.__game.state.get().validTiles; const k = [...v.keys].map((x) => x.split(',').map(Number)).sort((a, b) => a[1] - b[1] || a[0] - b[0])[0]; return { x: k[0], y: k[1] }; });
console.log('target valid tile', JSON.stringify(target));
for (let i = 0; i < 12; i++) await page.keyboard.press('ArrowLeft');
for (let i = 0; i < 12; i++) await page.keyboard.press('ArrowUp');
for (let i = 0; i < target.x; i++) await page.keyboard.press('ArrowRight');
for (let i = 0; i < target.y; i++) await page.keyboard.press('ArrowDown');
s = await st();
check('arrows reach the valid tile', s.hover.x === target.x && s.hover.y === target.y, JSON.stringify(s.hover));
await page.keyboard.press('Enter');
s = await st();
check('Enter places a road in the plan', s.draft.length === 1 && s.draft[0].x === target.x && s.draft[0].y === target.y, JSON.stringify(s.draft));
await page.keyboard.press('Enter');
s = await st();
check('Enter again on the same tile does not duplicate', s.draft.length === 1);
await page.keyboard.press('ArrowRight'); await page.keyboard.press('Enter');
await page.keyboard.press('ArrowRight'); await page.keyboard.press('Enter');
s = await st();
check('more tiles placed', s.draft.length >= 2, JSON.stringify(s.draft));
await page.keyboard.press('Escape');
s = await st();
check('Esc cancels build mode but keeps the plan', s.build === null && s.draft.length >= 2, JSON.stringify({ b: s.build, d: s.draft.length }));
await page.keyboard.press('Enter');
s = await st();
check('Enter without build mode selects the tile', s.sel && s.sel.kind === 'tile', JSON.stringify(s.sel));
await page.keyboard.press('Escape');
s = await st();
check('Esc clears the selection', s.sel === null);
// rotated camera: arrows follow the screen
await page.evaluate(() => { window.__game.rotate(1); window.__game.hover({ x: 6, y: 6 }); });
await page.waitForTimeout(700);
const before = (await st()).hover;
await page.keyboard.press('ArrowRight');
const after = (await st()).hover;
check('arrows follow the rotated view', before.x !== after.x || before.y !== after.y, `${JSON.stringify(before)} -> ${JSON.stringify(after)}`);
// person hover and click: project a person's head to the screen
await page.evaluate(() => window.__game.rotate(-1));
await page.waitForTimeout(700);
await page.evaluate(() => { window.__game.select(null); window.__game.hover(null); });
await page.waitForTimeout(300);
const people = await page.evaluate(() => window.__scene.peopleScreen());
check('20 people drawn', people.length === 20, String(people.length));
const p0 = people.find((p) => p.x > 250 && p.x < 1000 && p.y > 120 && p.y < 700);
await page.mouse.move(p0.x, p0.y);
await page.waitForTimeout(300);
const hv = await page.evaluate(async () => { const m = await import('/src/store/scene-people.ts'); let v; m.personHover.subscribe((x) => (v = x))(); return v; });
check('hover over a person reports a person', hv && hv.id === p0.id, JSON.stringify(hv));
await page.mouse.click(p0.x, p0.y);
await page.waitForTimeout(300);
s = await st();
check('click on a person selects the person', s.sel && s.sel.kind === 'person' && s.sel.id === p0.id, JSON.stringify(s.sel));
await page.screenshot({ path: process.env.SHOT ?? '/tmp/person-selected.png', clip: { x: 180, y: 50, width: 950, height: 745 } });
console.log('errors', JSON.stringify(errors));
await browser.close();
